"""The research graph in <PLSI_HOME>/research/: one Markdown file per item (`<project>/<id>.md`, the project's own page
is `<project>/<project>.md`), YAML frontmatter (kind, title, status; optional grade, evidence_class, sources, updated,
retire_reason) and [[id]] links in the body. Bots write the items (skill researcher/graph); this module only reads
them, checks them, writes the generated index.md and removes retired items. Opens as an Obsidian vault as it is."""

from __future__ import annotations

import re
from collections import Counter
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import yaml

from plsi import files, paths
from plsi.clock import now
from plsi.errors import NotFound, UsageError
from plsi.vocab import ResearchItemKind, ResearchStatus

INDEX, RETIRED = "index.md", "retired.md"
ID = re.compile(r"^[a-z0-9][a-z0-9-]{1,63}$")
LINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|([^\]]*))?\]\]")
STALE_DAYS = 30
OPEN = frozenset({ResearchStatus.OPEN, ResearchStatus.ACTIVE})


def root() -> Path:
    return paths.plsi_home() / "research"


def _parse(path: Path) -> tuple[dict[str, Any] | None, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---" not in text[4:]:
        return None, text
    head, _, body = text[4:].partition("\n---")
    try:
        meta = yaml.safe_load(head)
    except yaml.YAMLError:
        return None, body
    return (meta if isinstance(meta, dict) else None), body


def _updated(meta: dict[str, Any]) -> date | None:
    value = meta.get("updated")
    try:
        return value if isinstance(value, date) else date.fromisoformat(str(value)) if value else None
    except ValueError:
        return None


def _items() -> tuple[dict[str, dict[str, Any]], list[dict[str, str]]]:
    items: dict[str, dict[str, Any]] = {}
    problems: list[dict[str, str]] = []
    base = root()
    for path in sorted(base.glob("*/*.md")) if base.is_dir() else []:
        id_, project = path.stem, path.parent.name
        if id_ in items:
            problems.append({"id": id_, "problem": "duplicate_id", "detail": f"also in {items[id_]['project']}"})
            continue
        meta, body = _parse(path)
        if meta is None:
            problems.append({"id": id_, "problem": "bad_frontmatter", "detail": "no YAML frontmatter between --- lines"})
            meta = {}
        bad = [f"{k} {meta.get(k)!r}" for k, enum in (("kind", ResearchItemKind), ("status", ResearchStatus))
               if meta.get(k) not in tuple(enum)]
        if not ID.match(id_) or not meta.get("title") or bad:
            problems.append({"id": id_, "problem": "bad_item",
                             "detail": "; ".join([*(["file name is not a lowercase id"] if not ID.match(id_) else []),
                                                  *(["no title"] if not meta.get("title") else []),
                                                  *(f"unknown {b}" for b in bad)])})
        items[id_] = {"id": id_, "project": project, "kind": meta.get("kind"), "status": meta.get("status"),
                      "title": str(meta.get("title") or id_), "grade": meta.get("grade"), "updated": _updated(meta),
                      "retire_reason": meta.get("retire_reason"), "links_out": sorted({m[0].strip() for m in LINK.findall(body)}),
                      "path": path}
    return items, problems


def _graph() -> tuple[dict[str, dict[str, Any]], list[dict[str, str]]]:
    items, problems = _items()
    for item in items.values():
        item["links_in"] = sorted(i["id"] for i in items.values() if item["id"] in i["links_out"])
    for item in items.values():
        problems += [{"id": item["id"], "problem": "broken_link", "detail": f"[[{t}]] is no item"}
                     for t in item["links_out"] if t not in items]
        if item["kind"] != ResearchItemKind.PROJECT and not item["links_out"] and not item["links_in"]:
            problems.append({"id": item["id"], "problem": "orphan", "detail": "no links in or out"})
    problems += [{"id": p, "problem": "no_project_page", "detail": f"{p}/{p}.md is missing"}
                 for p in sorted({i["project"] for i in items.values()} - set(items))]
    return items, problems


def _public(item: dict[str, Any]) -> dict[str, Any]:
    out = {k: v for k, v in item.items() if k != "path" and v not in (None, [])}
    if item.get("updated"):
        out["updated"] = item["updated"].isoformat()
    return out


def _render(items: dict[str, dict[str, Any]], problems: list[dict[str, str]], stale: list[str]) -> str:
    lines = ["<!-- generated by plsi research index; edit the items, not this file -->", "# Research", ""]
    for project in sorted({i["project"] for i in items.values()}):
        page = items.get(project)
        lines += [f"## [[{project}]]" + (f" - {page['title']} ({page['status']})" if page else ""), ""]
        for kind in ResearchItemKind:
            group = sorted((i for i in items.values() if i["project"] == project and i["kind"] == kind and i["id"] != project),
                           key=lambda i: i["id"])
            if group:
                lines.append(f"**{kind}**")
                lines += [f"- [[{i['id']}]] {i['title']} ({i['status']}" + (f", {i['grade']}" if i["grade"] else "") + ")"
                          for i in group]
                lines.append("")
    ready = [i["id"] for i in items.values() if i["status"] == ResearchStatus.READY]
    for title, ids in (("Ready for evaluation", ready), (f"Stale (no update in {STALE_DAYS} days)", stale)):
        if ids:
            lines += [f"## {title}", "", *(f"- [[{i}]]" for i in sorted(ids)), ""]
    if problems:
        lines += ["## Problems", "", *(f"- {p['id']}: {p['problem']} ({p['detail']})" for p in problems), ""]
    return "\n".join(lines)


def index() -> dict[str, Any]:
    """`research index`: check every item and rewrite research/index.md; problems, ready, retire and stale ids."""
    items, problems = _graph()
    today = now().date()
    stale = sorted(i["id"] for i in items.values() if i["status"] in OPEN
                   and (i["updated"] is None or i["updated"] < today - timedelta(days=STALE_DAYS)))
    if items:
        files.atomic_write_text(root() / INDEX, _render(items, problems, stale))

    def by(s: str) -> list[str]:
        return sorted(i["id"] for i in items.values() if i["status"] == s)

    return {"root": str(root()), "items": len(items), "projects": len({i["project"] for i in items.values()}),
            "by_status": dict(Counter(str(i["status"]) for i in items.values())), "problems": problems,
            "ready": by(ResearchStatus.READY), "retire": by(ResearchStatus.RETIRE), "stale": stale}


def list_items(project: str | None = None, kind: str | None = None, status: str | None = None) -> list[dict[str, Any]]:
    """`research list`: items with their links, filtered."""
    items, _ = _graph()
    return [_public(i) for i in items.values()
            if project in (None, i["project"]) and kind in (None, i["kind"]) and status in (None, i["status"])]


def retire(id: str, reason: str) -> dict[str, Any]:  # noqa: A002 - CLI dest name
    """`research retire`: remove one item marked `retire`; links to it become its plain title; logged in retired.md."""
    items, _ = _graph()
    if id not in items:
        raise NotFound(f"{id!r} is not a research item", hint="plsi research list")
    item = items[id]
    if item["status"] != ResearchStatus.RETIRE:
        raise UsageError(f"{id!r} has status {item['status']!r}; only an item marked retire is removed",
                         hint="the owner sets status: retire and retire_reason first")
    if id == item["project"] and any(i["project"] == id and i["id"] != id for i in items.values()):
        raise UsageError(f"project {id!r} still has items; retire them first")
    for other in items.values():
        if id in other["links_out"]:
            text = other["path"].read_text(encoding="utf-8")
            files.atomic_write_text(other["path"], LINK.sub(
                lambda m: (m[2] or item["title"]) if m[1].strip() == id else m[0], text))
    item["path"].unlink()
    if not any(item["path"].parent.iterdir()):
        item["path"].parent.rmdir()
    log = root() / RETIRED
    prior = log.read_text(encoding="utf-8") if log.is_file() else "# Retired research items\n\n"
    entry = f"- {now().date().isoformat()} {item['title']} ({item['kind']}, {item['project']}): {reason}\n"
    files.atomic_write_text(log, prior + entry)
    return {"retired": id, "unlinked": item["links_in"], "index": index()}
